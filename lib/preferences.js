const defaults = {
  language: 'fr', theme: 'samani', colorA: '#ffb45f', colorB: '#ff91a8', angle: 135,
  background: 'gradient', media: null, blur: 12, brightness: 45, surface: 82,
  pauseBackground: true, reducedMotion: false, intro: true, alwaysOnTop: false,
  minimizeToTray: false, rememberWindow: true, startAtLogin: false,
  rpcEnabled: true, rpcClientId: '1563568424691437578', rpcShowTitle: true, rpcShowEpisode: true,
  rpcTemplate: '{title}', rpcButtons: true
};
const presets = {
  samani: { colorA: '#ffb45f', colorB: '#ff91a8', angle: 135 },
  sakura: { colorA: '#fda4af', colorB: '#c084fc', angle: 145 },
  ocean: { colorA: '#38bdf8', colorB: '#818cf8', angle: 120 },
  midnight: { colorA: '#94a3b8', colorB: '#475569', angle: 160 }
};
function sanitize(input = {}, base = defaults) {
  const output = { ...base };
  for (const key of Object.keys(defaults)) {
    const value = input[key];
    if (value === undefined) continue;
    if (typeof defaults[key] === 'boolean' && typeof value === 'boolean') output[key] = value;
  }
  if (['fr', 'en', 'ja'].includes(input.language)) output.language = input.language;
  if (Object.hasOwn(presets, input.theme)) output.theme = input.theme;
  if (['gradient', 'image', 'video', 'solid'].includes(input.background)) output.background = input.background;
  for (const key of ['colorA', 'colorB']) if (/^#[0-9a-f]{6}$/i.test(input[key] || '')) output[key] = input[key];
  for (const [key, min, max] of [['angle',0,360], ['blur',0,40], ['brightness',10,100], ['surface',35,100]]) {
    if (typeof input[key] === 'number' && Number.isFinite(input[key])) output[key] = Math.round(Math.min(max, Math.max(min, input[key])));
  }
  if (typeof input.rpcClientId === 'string' && /^\d{0,22}$/.test(input.rpcClientId)) output.rpcClientId = input.rpcClientId;
  if (typeof input.rpcTemplate === 'string') output.rpcTemplate = input.rpcTemplate.replace(/[\x00-\x1f]/g, '').slice(0, 128);
  // Media IDs are generated by the native file picker, never renderer paths.
  if (input.media === null || /^[a-f0-9]{32}\.(png|jpg|jpeg|webp|mp4|webm)$/.test(input.media || '')) output.media = input.media;
  return output;
}
function websiteCss(prefs) {
  const p = sanitize(prefs);
  const opacity = p.surface / 100;
  return `body,button,input,select{font-family:Beckman,'Segoe UI',sans-serif!important}:root{--samani-accent:${p.colorA};--samani-accent-secondary:${p.colorB};color-scheme:dark}html,body{background:transparent!important}body{--bg:transparent;--bg-root:transparent}header.asn-header,footer.asn-footer{background:rgba(13,14,20,${opacity})!important;backdrop-filter:blur(16px)}::selection{background:${p.colorB};color:#111}::-webkit-scrollbar{width:8px}::-webkit-scrollbar-thumb{background:#ffffff28;border-radius:8px}a:focus-visible,button:focus-visible{outline:2px solid ${p.colorA};outline-offset:3px}${p.reducedMotion?'*,*::before,*::after{scroll-behavior:auto!important;animation-duration:.01ms!important;transition-duration:.01ms!important}':''}`;
}
module.exports = { defaults, presets, sanitize, websiteCss };
